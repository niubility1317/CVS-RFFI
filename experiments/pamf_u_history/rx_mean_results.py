"""Read only completed RX-mean decisions and existing scores; no new truth query."""
import argparse
import itertools
import json
from pathlib import Path,PurePosixPath
from .rx_mean_source import RUN,BASELINE,METHODS,SEEDS,TASKS
from .covariance_three_results import REFERENCES,COUNTS,summarize as summarize_matrix
from .fonly_results import save,VIEWS


def expected_run(method,seed):
    if method not in (*METHODS,*REFERENCES) or seed not in SEEDS:raise ValueError('Exact two-scope three-seed RX-mean matrix and completed references required')
    return BASELINE if method in REFERENCES else RUN


def locations(rt):
    root=PurePosixPath(rt['project'])/'runs';rows=[]
    for method,seed in itertools.product((*METHODS,*REFERENCES),SEEDS):
        rid='F0-'+method+'-s'+str(seed);run=expected_run(method,seed)
        rows.append(dict(method=method,model_seed=seed,run_id=run,row_id=rid,root=str(root/run/'readouts'/rid)))
    return rows


def collection_script(rt,*,run_id=RUN,methods=METHODS,references=REFERENCES,row_locations=None,completion_status='RX_MEAN_THREE_SEED_COMPLETE',models=6,jobs=22):
    if rt['run_id']!=run_id:raise ValueError('One actual RX-mean release runtime only')
    script=r'''
import json
from pathlib import Path
import numpy as np
rt=RUNTIME;rows=ROWS;methods=METHODS;seeds=SEEDS;tasks=TASKS;views=VIEWS;counts=COUNTS;references=REFERENCES
root=Path(rt['run_root']);done=json.loads((root/'complete.json').read_text());state=json.loads((root/'pipeline_state.json').read_text())
if (done['status']!=COMPLETION_STATUS or done['models']!=MODEL_COUNT or done['methods']!=list(methods)
 or done['model_seeds']!=list(seeds) or not done['raw_only'] or not done['truth_last']
 or state['status']!=COMPLETION_STATUS or len(state['jobs'])!=JOB_COUNT
 or any(v['status']!='COMPLETE' for v in state['jobs'].values())):raise ValueError('All registered models and independent scores must finish first')
scores=[];physical={};decisions=0
for row in rows:
 folder=Path(row['root']);prediction=json.loads((folder/'predictions/complete.json').read_text());scored=json.loads((folder/'scores/complete.json').read_text())
 if prediction['status']!='ALL_PREDICTIONS_COMPLETE' or scored['status']!='SCORED_COMPLETE':raise ValueError('Completed frozen row artifacts required')
 score=json.loads((folder/'scores/scores.json').read_text())
 if score['run_id']!=row['run_id'] or score['row_id']!=row['row_id'] or score['model_seed']!=row['model_seed']:raise ValueError('Actual saved score row identity differs')
 scores.append(dict(method=row['method'],model_seed=row['model_seed'],score=score))
 for task in tasks:
  with np.load(folder/'predictions'/task/'predictions.npz',allow_pickle=False) as a:
   n=counts[task];ids=a['ids'].copy()
   if ids.shape!=(n,) or len(np.unique(ids))!=n:raise ValueError('Original complete unique physical population required')
   physical[row['method'],row['model_seed'],task]=ids
   if row['method'] in methods:
    if set(a.files)!={'ids',*('raw__'+v for v in views)}:raise ValueError('Candidate has undeclared inference readouts')
    for view in views:
     pred=a['raw__'+view]
     if pred.shape!=(n,) or pred.dtype.kind not in 'iu' or pred.min()<0 or pred.max()>=6:raise ValueError('Finite six-class integer decisions required')
     decisions+=n
checks=[]
for method in methods:
 for seed in seeds:
  for reference in references:
   for task in tasks:
    if not np.array_equal(physical[method,seed,task],physical[reference,seed,task]):raise ValueError('Same-seed physical decision order differs')
    checks.append(dict(method=method,model_seed=seed,reference=reference,task=task,count=counts[task],exact_ID_order=True))
print(json.dumps(dict(status='THREE_SEED_FROZEN_RESULTS_COLLECTED',scores=scores,pairing_checks=checks,
 logical_candidate_raw_decisions=decisions,truth_reads=0,IQ_reads=0,weight_reads=0)))
'''
    for name,value in [('RUNTIME',rt),('ROWS',locations(rt) if row_locations is None else row_locations),('METHODS',methods),('SEEDS',SEEDS),('TASKS',TASKS),('VIEWS',VIEWS),('COUNTS',COUNTS),('REFERENCES',references),
        ('COMPLETION_STATUS',completion_status),('MODEL_COUNT',models),('JOB_COUNT',jobs)]:script=script.replace(name,repr(value))
    compile(script,'frozen_rx_mean_collection','exec');return script


def collect(runtime,output):
    from experiments.cric_dura_comparison.publish import ssh
    out=Path(output)
    if out.exists():raise FileExistsError('Preserve existing frozen result bundle')
    rt=json.loads(Path(runtime).read_text(encoding='utf-8'));result=ssh(collection_script(rt))
    # Validate the full matrix before persisting the readback, with no new IQ,
    # truth, weights or decisions generated by this analysis process.
    summarize(result);out.parent.mkdir(parents=True,exist_ok=True)
    with out.open('x',encoding='utf-8') as f:json.dump(result,f,indent=2);f.write('\n')
    print(json.dumps(dict(status=result['status'],score_rows=len(result['scores']),physical_pairings=len(result['pairing_checks']),raw_candidate_decisions=result['logical_candidate_raw_decisions'])))


def summarize(bundle):
    return summarize_matrix(bundle,methods=METHODS,run_id=RUN,row_run=expected_run,status='ANALYZED_RX_MEAN_THREE_SEED_FONLY')


def analyze(bundle,output):
    result,tables=summarize(json.loads(Path(bundle).read_text(encoding='utf-8')));out=Path(output);out.mkdir(parents=True,exist_ok=True)
    (out/'analysis.json').write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    for name,rows in tables.items():save(out/(name+'.csv'),rows)
    print(json.dumps(dict(status=result['status'],overall=[r for r in result['summary'] if r['population']=='overall_168000'],full_goal_complete=False)))
    return result


if __name__=='__main__':
    p=argparse.ArgumentParser();sub=p.add_subparsers(dest='action',required=True)
    c=sub.add_parser('collect');c.add_argument('--runtime',required=True);c.add_argument('--output',required=True)
    a=sub.add_parser('analyze');a.add_argument('--bundle',required=True);a.add_argument('--output',required=True)
    args=p.parse_args();collect(args.runtime,args.output) if args.action=='collect' else analyze(args.bundle,args.output)
